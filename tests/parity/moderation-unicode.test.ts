import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { describe, expect, it } from 'vitest';
import { IGNORABLE_RANGES, MARK_RANGES, UNICODE_VERSION } from '@/lib/moderation/unicodeData';

// src/lib/moderation/unicodeData.ts is generated from Node's Unicode tables. Regenerate (then re-run GEN_MOD=1 for the
// SQL fixture and paste the classes into a NEW migration) with:  GEN_UNICODE=1 pnpm vitest run tests/parity/moderation-unicode.test.ts
const FILE = path.resolve(__dirname, '../../src/lib/moderation/unicodeData.ts');

type R = [number, number][];
function ranges(re: RegExp): R {
  const out: R = [];
  let s = -1;
  let p = -2;
  for (let c = 0; c <= 0x10ffff; c++) {
    if (c >= 0xd800 && c <= 0xdfff) continue;
    if (re.test(String.fromCodePoint(c))) {
      if (c !== p + 1) {
        if (s >= 0) out.push([s, p]);
        s = c;
      }
      p = c;
    }
  }
  if (s >= 0) out.push([s, p]);
  return out;
}

function render(m: R, di: R): string {
  const fmt = (a: R) => a.map(([x, y]) => `[0x${x.toString(16).toUpperCase()},0x${y.toString(16).toUpperCase()}]`);
  const chunk = (arr: string[]) => {
    const lines: string[] = [];
    for (let i = 0; i < arr.length; i += 8) lines.push(`  ${arr.slice(i, i + 8).join(', ')},`);
    return lines.join('\n');
  };
  return `// GENERATED by tests/parity/moderation-unicode.test.ts (GEN_UNICODE=1) from Node ${process.versions.node} / Unicode ${process.versions.unicode}.
// Shared by the TS moderation forms (src/lib/moderation/normalize.ts) and the SQL ones (supabase/migrations/0002_hardening.sql,
// BEGIN:MOD_CLASSES): the parity test checks that the SQL regex classes are built from exactly these ranges.

export const UNICODE_VERSION = "${process.versions.unicode}";

/** General_Category = Mark (Mn, Mc, Me): combining marks left after NFKC/NFC are stripped before matching. */
export const MARK_RANGES: readonly (readonly [number, number])[] = [
${chunk(fmt(m))}
];

/** Default_Ignorable_Code_Point (zero-width, bidi controls, fillers, variation selectors, tags...) plus U+2800 (braille blank). */
export const IGNORABLE_RANGES: readonly (readonly [number, number])[] = [
${chunk(fmt(di))}
  [0x2800,0x2800],
];
`;
}

describe('moderation Unicode data', () => {
  const m = ranges(/^\p{M}$/u);
  const di = ranges(/^\p{Default_Ignorable_Code_Point}$/u);
  if (process.env.GEN_UNICODE) writeFileSync(FILE, render(m, di));

  it('covers the spec fillers and Vietnamese combining marks', () => {
    const inR = (rs: readonly (readonly [number, number])[], c: number) => rs.some(([a, b]) => c >= a && c <= b);
    for (const c of [0x3164, 0x115f, 0x1160, 0x2800, 0x180e, 0x200b, 0x200f, 0x2060, 0x2064, 0xfeff, 0x034f]) {
      expect(inR(IGNORABLE_RANGES, c), c.toString(16)).toBe(true);
    }
    for (const c of [0x0300, 0x0301, 0x0303, 0x0309, 0x0323, 0x0302, 0x0306, 0x031b, 0x0334, 0x20dd]) {
      expect(inR(MARK_RANGES, c), c.toString(16)).toBe(true);
    }
  });

  it('matches this Node runtime when the Unicode version is the same', () => {
    if (process.versions.unicode !== UNICODE_VERSION) return; // other Node: the committed data stays authoritative
    expect(readFileSync(FILE, 'utf8').split('\n').slice(3).join('\n')).toBe(render(m, di).split('\n').slice(3).join('\n'));
  });
});
