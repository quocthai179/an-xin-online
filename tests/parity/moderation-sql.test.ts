import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { describe, expect, it } from 'vitest';
import { isBlocked } from '@/lib/moderation/blocklist';
import { hasPii } from '@/lib/moderation/pii';
import { exactForm, looseForm } from '@/lib/moderation/normalize';
import { MUST_BLOCK, MUST_PASS, PII_NO, PII_YES } from './moderation-cases';

// supabase/tests/85_moderation_parity.sql is GENERATED from the TS moderation code: SQL must produce exactly the same
// is_blocked / has_pii / loose / exact results for the shared corpus. Regenerate with:
//   GEN_MOD=1 pnpm vitest run tests/parity/moderation-sql.test.ts
const FILE = path.resolve(__dirname, '../../supabase/tests/85_moderation_parity.sql');

/** SQL literal; non-printable / invisible code points as U&'' escapes so the file stays readable and diff-safe. */
function lit(s: string): string {
  let out = '';
  let esc = false;
  for (const ch of s) {
    const cp = ch.codePointAt(0)!;
    const visible = /[\p{L}\p{N}\p{P}\p{S} ]/u.test(ch) && !/\p{M}/u.test(ch);
    if (ch === "'") out += "''";
    else if (ch === '\\') { out += '\\\\'; esc = true; }
    else if (visible) out += ch;
    else { out += cp > 0xffff ? `\\+${cp.toString(16).toUpperCase().padStart(6, '0')}` : `\\${cp.toString(16).toUpperCase().padStart(4, '0')}`; esc = true; }
  }
  return esc ? `U&'${out}'` : `'${out}'`;
}

function build(): string {
  const corpus = [...new Set([...MUST_BLOCK, ...MUST_PASS, ...PII_YES, ...PII_NO])];
  const rows = corpus.map((t) =>
    `    (${lit(t)}, ${isBlocked(t)}, ${hasPii(t)}, ${lit(looseForm(t).trim())}, ${lit(exactForm(t))})`);
  return [
    '-- GENERATED by tests/parity/moderation-sql.test.ts (GEN_MOD=1) from src/lib/moderation/*. Do not edit by hand.',
    '-- SQL moderation (private.is_blocked / has_pii / loose / exact form) must equal the TS implementation on this corpus.',
    '\\set ON_ERROR_STOP 1',
    'begin;',
    'do $$',
    'declare r record; v_bad text[] := \'{}\'; v_exact text;',
    'begin',
    '  for r in select * from (values',
    rows.join(',\n'),
    '  ) t(txt, blocked, pii, loose, exact) loop',
    "    v_exact := ' ' || btrim(regexp_replace(private.mod_base(r.txt), '[^[:alnum:]]+', ' ', 'g')) || ' ';",
    "    if private.is_blocked(r.txt) is distinct from r.blocked then v_bad := v_bad || ('is_blocked ' || r.txt || ' expected ' || r.blocked); end if;",
    "    if private.has_pii(r.txt) is distinct from r.pii then v_bad := v_bad || ('has_pii ' || r.txt || ' expected ' || r.pii); end if;",
    "    if private.loose(r.txt) is distinct from r.loose then v_bad := v_bad || ('loose ' || r.txt || ': ' || private.loose(r.txt) || ' <> ' || r.loose); end if;",
    "    if v_exact is distinct from r.exact then v_bad := v_bad || ('exact ' || r.txt || ': ' || v_exact || ' <> ' || r.exact); end if;",
    '  end loop;',
    "  if cardinality(v_bad) > 0 then raise exception 'FAIL: TS/SQL moderation mismatch: %', array_to_string(v_bad, ' | '); end if;",
    `  perform tests.pass('moderation parity with TS (${corpus.length} cases x 4 functions)');`,
    'end $$;',
    'rollback;',
    '',
  ].join('\n');
}

describe('supabase/tests/85_moderation_parity.sql', () => {
  if (process.env.GEN_MOD) writeFileSync(FILE, build());
  it('is up to date with src/lib/moderation and tests/parity/moderation-cases.ts', () => {
    expect(readFileSync(FILE, 'utf8')).toBe(build());
  });
});
